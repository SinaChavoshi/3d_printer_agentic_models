def resample(t, x, dt=None, max_n=2**20):
    if dt is None:
        dt = float(np.median(np.diff(t)))
    n = int(math.floor((t[-1] - t[0]) / dt)) + 1
    if n > max_n:
        dt = (t[-1] - t[0]) / (max_n - 1)
        n = max_n
    tu = t[0] + dt * np.arange(n)
    if x.ndim == 1:
        return tu, np.interp(tu, t, x), dt
    return (
        tu,
        np.column_stack([np.interp(tu, t, x[:, j]) for j in range(x.shape[1])]),
        dt,
    )


def spectrum(t, x):
    """One-sided amplitude spectrum (Hann window, linear detrend)."""
    tu, xu, dt = resample(t, x)
    n = len(xu)
    if n < 16:
        return None
    k = np.arange(n)
    p = np.polyfit(k, xu, 1)
    xd = xu - np.polyval(p, k)
    w = np.hanning(n)
    X = np.fft.rfft(xd * w)
    f = np.fft.rfftfreq(n, dt)
    amp = 2.0 * np.abs(X) / w.sum()  # sinusoid amplitude estimate
    return f, amp


def dominant(t, x, fmin, fmax):
    sp = spectrum(t, x)
    if sp is None:
        return None, None, None
    f, amp = sp
    band = (f >= fmin) & (f <= fmax)
    if band.sum() < 3:
        return None, None, sp
    idx = np.nonzero(band)[0]
    i = idx[np.argmax(amp[idx])]
    fp = f[i]
    if 0 < i < len(f) - 1:  # parabolic interpolation of the peak
        y0, y1, y2 = amp[i - 1], amp[i], amp[i + 1]
        den = y0 - 2 * y1 + y2
        if den != 0:
            fp = f[i] + 0.5 * (y0 - y2) / den * (f[1] - f[0])
    return float(fp), float(amp[i]), sp


def stats(x):
    x = np.asarray(x, dtype=float)
    x = x[np.isfinite(x)]
    if len(x) == 0:
        return dict(mean=np.nan, std=np.nan, p2p=np.nan, min=np.nan, max=np.nan)
    return dict(
        mean=float(x.mean()),
        std=float(x.std()),
        p2p=float(x.max() - x.min()),
        min=float(x.min()),
        max=float(x.max()),
    )


def cumtrapz(y, t):
    out = np.zeros_like(y, dtype=float)
    out[1:] = np.cumsum(0.5 * (y[1:] + y[:-1]) * np.diff(t))
    return out


