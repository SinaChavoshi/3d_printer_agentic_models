def parse_log(path: Path):
    """Parse sixDoF 'report on' blocks from a solver log. Restarted/appended
    logs are handled: the last block per time value wins."""
    rec = {}
    t = None
    cur = None
    with open(path, errors="replace") as fh:
        for line in fh:
            m = RE_TIME.match(line)
            if m:
                t = float(m.group(1))
                cur = rec.setdefault(t, {})
                continue
            if cur is None:
                continue
            if line.startswith("6-DoF rigid body motion"):
                cur["_block"] = True
                continue
            for key, rx, n in (
                ("cor", RE_COR, 3),
                ("com", RE_COM, 3),
                ("Q", RE_ORI, 9),
                ("v", RE_VEL, 3),
                ("omega", RE_OMG, 3),
            ):
                m = rx.match(line)
                if m:
                    vals = _floats(m.group(1))
                    if len(vals) == n:
                        cur[key] = vals
                    break
            else:
                m = RE_RES.search(line)
                if m:
                    vec = _floats(m.group(2))
                    frc = _floats(m.group(4))
                    if len(vec) == 3 and len(frc) == 3:
                        cur.setdefault("restraints", {})[m.group(1)] = (
                            vec,
                            float(m.group(3)),
                            frc,
                        )
    times = sorted(
        k for k, r in rec.items() if all(q in r for q in ("cor", "Q", "omega"))
    )
    if not times:
        return None
    out = dict(source=str(path), t=np.array(times))
    out["cor"] = np.array([rec[k]["cor"] for k in times])
    out["com"] = np.array([rec[k].get("com", rec[k]["cor"]) for k in times])
    out["Q"] = np.array([rec[k]["Q"] for k in times]).reshape(-1, 3, 3)
    out["v"] = np.array([rec[k].get("v", [np.nan] * 3) for k in times])
    out["omega"] = np.array([rec[k]["omega"] for k in times])
    names = sorted({n for k in times for n in rec[k].get("restraints", {})})
    res = {}
    for nme in names:
        vec = np.full((len(times), 3), np.nan)
        length = np.full(len(times), np.nan)
        frc = np.full((len(times), 3), np.nan)
        for i, k in enumerate(times):
            r = rec[k].get("restraints", {}).get(nme)
            if r:
                vec[i], length[i], frc[i] = r
        res[nme] = dict(vec=vec, length=length, force=frc)
    out["restraints"] = res
    return out


def euler_xyz_to_matrix(ang):
    """OpenFOAM quaternion::XYZ convention: R = Rx(a) Ry(b) Rz(c)."""
    a, b, c = ang[:, 0], ang[:, 1], ang[:, 2]
    ca, sa, cb, sb, cc, sc = (
        np.cos(a),
        np.sin(a),
        np.cos(b),
        np.sin(b),
        np.cos(c),
        np.sin(c),
    )
    R = np.empty((len(a), 3, 3))
    R[:, 0, 0] = cb * cc
    R[:, 0, 1] = -cb * sc
    R[:, 0, 2] = sb
    R[:, 1, 0] = ca * sc + sa * sb * cc
    R[:, 1, 1] = ca * cc - sa * sb * sc
    R[:, 1, 2] = -sa * cb
    R[:, 2, 0] = sa * sc - ca * sb * cc
    R[:, 2, 1] = sa * cc + ca * sb * sc
    R[:, 2, 2] = ca * cb
    return R


def parse_state_dat(files):
    rows = []
    degrees = False
    for f in files:
        with open(f, errors="replace") as fh:
            for line in fh:
                s = line.strip()
                if not s:
                    continue
                if s.startswith("#"):
                    if "Angle Units" in s and "degree" in s.lower():
                        degrees = True
                    continue
                vals = _floats(s.replace("(", " ").replace(")", " "))
                if len(vals) >= 16:
                    rows.append(vals[:16])
    if not rows:
        return None
    arr = np.array(rows)
    arr = arr[np.argsort(arr[:, 0], kind="stable")]
    _, keep = np.unique(arr[::-1, 0], return_index=True)  # last occurrence wins
    arr = arr[::-1][keep]
    ang = arr[:, 7:10]
    omg = arr[:, 13:16]
    if degrees:
        ang = np.radians(ang)
        omg = np.radians(omg)
    return dict(
        source=",".join(str(f) for f in files),
        t=arr[:, 0],
        cor=arr[:, 1:4],
        com=arr[:, 4:7],
        Q=euler_xyz_to_matrix(ang),
        v=arr[:, 10:13],
        omega=omg,
        restraints={},
    )


def _dict_entry(text, key, n):
    m = re.search(r"\b" + key + r"\s*" + VEC + r"\s*;", text)
    if not m:
        return None
    vals = _floats(m.group(1))
    return vals if len(vals) == n else None


def parse_uniform_states(bg: Path, inertia_diag):
    """Fallback: <time>/uniform/sixDoFRigidBodyMotionState at write times."""
    cands = list(bg.glob("[0-9]*/uniform/sixDoFRigidBodyMotionState"))
    if not cands:
        cands = list(bg.glob("processor0/[0-9]*/uniform/sixDoFRigidBodyMotionState"))
    rows = []
    for f in cands:
        try:
            t = float(f.parent.parent.name)
            txt = f.read_text(errors="replace")
        except (ValueError, OSError):
            continue
        cor = _dict_entry(txt, "centreOfRotation", 3)
        Q = _dict_entry(txt, "orientation", 9)
        v = _dict_entry(txt, "velocity", 3)
        pi = _dict_entry(txt, "angularMomentum", 3)
        if None in (cor, Q, v, pi):
            continue  # binary-format dictionaries are skipped
        Qm = np.array(Q).reshape(3, 3)
        omega = Qm @ (np.array(pi) / np.asarray(inertia_diag))
        rows.append((t, cor, Qm, v, omega))
    if len(rows) < 2:
        return None
    rows.sort(key=lambda r: r[0])
    return dict(
        source=f"{bg}/<time>/uniform/sixDoFRigidBodyMotionState",
        t=np.array([r[0] for r in rows]),
        cor=np.array([r[1] for r in rows]),
        com=np.array([r[1] for r in rows]),
        Q=np.array([r[2] for r in rows]),
        v=np.array([r[3] for r in rows]),
        omega=np.array([r[4] for r in rows]),
        restraints={},
    )


def parse_forces(bg: Path, name="lureForces"):
    files = sorted(bg.glob(f"postProcessing/{name}/*/force.dat"))
    if not files:
        files = sorted(bg.glob(f"postProcessing/{name}/*/forces.dat"))
    rows = []
    for f in files:
        with open(f, errors="replace") as fh:
            for line in fh:
                s = line.strip()
                if not s or s.startswith("#"):
                    continue
                vals = _floats(s.replace("(", " ").replace(")", " "))
                if len(vals) >= 10:
                    rows.append(vals[:10])
    if not rows:
        return None
    arr = np.array(rows)
    arr = arr[np.argsort(arr[:, 0], kind="stable")]
    _, keep = np.unique(arr[::-1, 0], return_index=True)
    arr = arr[::-1][keep]
    return dict(
        source=",".join(map(str, files)),
        t=arr[:, 0],
        total=arr[:, 1:4],
        pressure=arr[:, 4:7],
        viscous=arr[:, 7:10],
    )


def write_vtp_series(bg: Path, outdir: Path):
    """ParaView .series index for postProcessing/lureSurface/<time>/*.vtp."""
    written = []
    groups = {}
    for f in bg.glob("postProcessing/lureSurface/*/*.vtp"):
        try:
            t = float(f.parent.name)
        except ValueError:
            continue
        groups.setdefault(f.name, []).append((t, f))
    for fname, items in groups.items():
        items.sort()
        entries = [
            {"name": str(Path(*_relpath(f, outdir))), "time": t} for t, f in items
        ]
        dst = outdir / f"lureSurface_{Path(fname).stem}.vtp.series"
        dst.write_text(
            json.dumps({"file-series-version": "1.0", "files": entries}, indent=1)
        )
        written.append(str(dst))
    return written


def _relpath(target: Path, start: Path):
    target, start = target.resolve(), start.resolve()
    t_parts, s_parts = target.parts, start.parts
    i = 0
    while i < min(len(t_parts), len(s_parts)) and t_parts[i] == s_parts[i]:
        i += 1
    return [".."] * (len(s_parts) - i) + list(t_parts[i:])


