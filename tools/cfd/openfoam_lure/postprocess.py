#!/usr/bin/env python3
"""
postprocess.py - analyse a towed-lure 6-DoF OpenFOAM run produced from a case
generated by prepare_case.py.

6-DoF state sources (first one found wins unless --source is given):
  log      background/log.overPimpleDyMFoam - the sixDoFRigidBodyMotion solver
           prints, every time step ('report on'):
               6-DoF rigid body motion
                   Centre of rotation: (x y z)
                   Centre of mass: (x y z)
                   Orientation: (xx xy xz yx yy yz zx zy zz)
                   Linear velocity: (x y z)
                   Angular velocity: (x y z)
           and one line per restraint:
               Restraint leader:  attachmentPt - anchor (x y z) spring length L force (x y z)
  dat      postProcessing/<name>/<t0>/sixDoFRigidBodyState.dat written by the
           'sixDoFRigidBodyState' function object (columns: Time,
           centreOfRotation, centreOfMass, rotation [XYZ Euler angles],
           velocity, omega). NOTE: in OpenFOAM v2412 this function object does
           not work with dynamicOversetFvMesh; supported for other set-ups.
  uniform  <time>/uniform/sixDoFRigidBodyMotionState (write times only; ASCII).

Forces: postProcessing/lureForces/<t0>/force.dat (forces function object).

Outputs (default <case>/postprocess/): timeseries.csv, summary.csv,
summary.json, roll.png, attitude.png, position.png, trajectory.png,
spectra.png, line_forces.png and lureSurface_*.vtp.series (ParaView index of
the high-rate lure-surface VTK output).

Conventions (case frame): flow +x, z up; lure long axis initially +x
(nose at min x).
  roll  : rotation about the lure's own long axis; + = right-handed about the
          tail-pointing axis (counter-clockwise seen from behind the lure)
  yaw   : rotation about +z (+ = tail swings to +y);  pitch: + = nose up
  line elevation: angle of the leader above horizontal, measured from the
          tow eye towards the boat-side anchor (+ = anchor above the lure)

Requires numpy and matplotlib.
"""

from __future__ import annotations

import argparse
import csv
import json
import math
import re
import sys
from pathlib import Path

import numpy as np

VEC = r"\(\s*([^()]*?)\s*\)"
RE_TIME = re.compile(r"^Time = ([-+0-9.eE]+)\s*$")
RE_COR = re.compile(r"^\s*Centre of rotation:\s*" + VEC)
RE_COM = re.compile(r"^\s*Centre of mass:\s*" + VEC)
RE_ORI = re.compile(r"^\s*Orientation:\s*" + VEC)
RE_VEL = re.compile(r"^\s*Linear velocity:\s*" + VEC)
RE_OMG = re.compile(r"^\s*Angular velocity:\s*" + VEC)
RE_RES = re.compile(
    r"Restraint\s+(\S+):\s+attachmentPt - anchor\s*"
    + VEC
    + r"\s*spring length\s+(\S+)\s+force\s*"
    + VEC
)


def _floats(text):
    return [float(v) for v in text.replace(",", " ").split()]


