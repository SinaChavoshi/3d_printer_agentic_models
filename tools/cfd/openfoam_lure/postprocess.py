def write_outputs(outdir, S, sug, warnings, ser, meta, make_plots=True):
    outdir.mkdir(parents=True, exist_ok=True)
    t = ser["t"]
    cols = {
        "time_s": t,
        "com_dx_mm": ser["disp"][:, 0] * 1e3,
        "com_dy_mm": ser["disp"][:, 1] * 1e3,
        "com_dz_mm": ser["disp"][:, 2] * 1e3,
        "roll_cum_deg": np.degrees(ser["roll_cum"]),
        "roll_rate_rpm": ser["rate"] * 60 / (2 * math.pi),
        "roll_deg": ser["roll_w"],
        "yaw_deg": ser["yaw"],
        "pitch_deg": ser["pitch"],
        "line_elevation_deg": ser["elev"],
        "line_azimuth_deg": ser["azim"],
        "line_length_m": ser["llen"],
        "line_tension_N": ser["tension"],
    }
    if ser["tail"] is not None:
        cols["tail_dy_mm"] = (ser["tail"][:, 1] - ser["tail"][0, 1]) * 1e3
        cols["tail_dz_mm"] = (ser["tail"][:, 2] - ser["tail"][0, 2]) * 1e3
    if ser["F"] is not None:
        cols["Fx_N"], cols["Fy_N"], cols["Fz_N"] = ser["F"].T
    keys = list(cols)
    with open(outdir / "timeseries.csv", "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(keys)
        for i in range(len(t)):
            w.writerow([f"{cols[k][i]:.8g}" for k in keys])
    with open(outdir / "summary.csv", "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["metric", "value", "unit", "description"])
        for k, v in S.items():
            w.writerow([k, v["value"], v["unit"], v["description"]])
    (outdir / "summary.json").write_text(
        json.dumps(
            dict(
                meta=meta,
                metrics=S,
                suggestions_for_prepare_case=sug,
                warnings=warnings,
            ),
            indent=2,
            default=float,
        )
    )
    if not make_plots:
        return []
    return make_figures(outdir, ser, S)


def make_figures(outdir, ser, S):
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    t, win = ser["t"], ser["win"]
    t0 = t[win][0]
    files = []

    def shade(ax):
        ax.axvspan(t[0], t0, color="0.9", lw=0, label="_skip")
        ax.grid(True, alpha=0.3)

    fig, ax = plt.subplots(2, 1, figsize=(9, 6), sharex=True)
    ax[0].plot(t, ser["roll_cum"] / (2 * math.pi))
    ax[0].set_ylabel("rotations [rev]")
    ax[0].set_title("Roll / spin about the lure axis (+ = CCW seen from behind)")
    ax[1].plot(t, ser["rate"] * 60 / (2 * math.pi))
    ax[1].set_ylabel("roll rate [rpm]")
    ax[1].set_xlabel("time [s]")
    for a in ax:
        shade(a)
    fig.tight_layout()
    files.append(outdir / "roll.png")
    fig.savefig(files[-1], dpi=120)
    plt.close(fig)

    fig, ax = plt.subplots(3, 1, figsize=(9, 7), sharex=True)
    for a, y, lab in zip(
        ax,
        (ser["yaw"], ser["pitch"], ser["roll_w"]),
        ("yaw [deg]", "pitch [deg] (+ nose up)", "roll [deg] (wrapped)"),
    ):
        a.plot(t, y)
        a.set_ylabel(lab)
        shade(a)
    ax[0].set_title("Attitude relative to the initial orientation")
    ax[-1].set_xlabel("time [s]")
    fig.tight_layout()
    files.append(outdir / "attitude.png")
    fig.savefig(files[-1], dpi=120)
    plt.close(fig)

    fig, ax = plt.subplots(3, 1, figsize=(9, 7), sharex=True)
    for j, (a, lab) in enumerate(
        zip(ax, ("surge dx [mm]", "sway dy [mm]", "heave dz [mm]"))
    ):
        a.plot(t, ser["disp"][:, j] * 1e3, label="centre of mass")
        if j > 0 and ser["tail"] is not None:
            a.plot(
                t,
                (ser["tail"][:, j] - ser["tail"][0, j]) * 1e3,
                lw=0.8,
                label="tail tip",
            )
            a.legend(loc="upper right", fontsize=8)
        a.set_ylabel(lab)
        shade(a)
    ax[0].set_title("Translation of the lure")
    ax[-1].set_xlabel("time [s]")
    fig.tight_layout()
    files.append(outdir / "position.png")
    fig.savefig(files[-1], dpi=120)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(6, 6))
    d = ser["disp"][win] * 1e3
    ax.plot(d[:, 1], d[:, 2], lw=0.8, label="centre of mass")
    if ser["tail"] is not None:
        tl = (ser["tail"][win] - ser["tail"][0]) * 1e3
        ax.plot(tl[:, 1], tl[:, 2], lw=0.6, alpha=0.7, label="tail tip")
    ax.set_xlabel("dy [mm]")
    ax.set_ylabel("dz [mm]")
    ax.set_aspect("equal", adjustable="datalim")
    ax.set_title("Trajectory seen from behind (analysis window)")
    ax.grid(True, alpha=0.3)
    ax.legend(fontsize=8)
    fig.tight_layout()
    files.append(outdir / "trajectory.png")
    fig.savefig(files[-1], dpi=120)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(9, 5))
    tw = t[win]
    sigs = [
        ("yaw [deg]", ser["yaw"][win]),
        ("sway [mm]", ser["disp"][win, 1] * 1e3),
        ("heave [mm]", ser["disp"][win, 2] * 1e3),
    ]
    if ser["F"] is not None and np.isfinite(ser["F"][win, 1]).all():
        sigs.append(("side force [mN]", ser["F"][win, 1] * 1e3))
    for lab, y in sigs:
        sp = spectrum(tw, y)
        if sp is None:
            continue
        f, amp = sp
        band = (f > 0) & (f <= ser["fmax"])
        ax.semilogy(f[band], np.maximum(amp[band], 1e-12), label=lab, lw=0.9)
    ax.axvline(ser["fmin"], color="0.5", ls=":", lw=0.8)
    ax.set_xlim(0, min(ser["fmax"], 30.0))
    ax.set_xlabel("frequency [Hz]")
    ax.set_ylabel("amplitude spectrum")
    ax.set_title("Spectra (analysis window, Hann window)")
    ax.grid(True, which="both", alpha=0.3)
    ax.legend(fontsize=8)
    fig.tight_layout()
    files.append(outdir / "spectra.png")
    fig.savefig(files[-1], dpi=120)
    plt.close(fig)

    n = 3 if ser["F"] is not None else 2
    fig, ax = plt.subplots(n, 1, figsize=(9, 2.4 * n + 1), sharex=True)
    ax[0].plot(t, ser["elev"], label="elevation")
    ax[0].plot(t, ser["azim"], label="azimuth")
    ax[0].set_ylabel("leader angle [deg]")
    ax[0].legend(fontsize=8)
    ax[1].plot(t, ser["tension"])
    ax[1].axhline(0.0, color="k", lw=0.6)
    ax[1].set_ylabel("tension [N]\n(<0: compression)")
    if ser["F"] is not None:
        for j, lab in enumerate(("Fx (drag)", "Fy (side)", "Fz (lift)")):
            ax[2].plot(t, ser["F"][:, j], label=lab, lw=0.9)
        ax[2].set_ylabel("force [N]")
        ax[2].legend(fontsize=8)
    for a in ax:
        shade(a)
    ax[0].set_title("Leader and hydrodynamic forces")
    ax[-1].set_xlabel("time [s]")
    fig.tight_layout()
    files.append(outdir / "line_forces.png")
    fig.savefig(files[-1], dpi=120)
    plt.close(fig)
    return [str(f) for f in files]


def build_parser():
    p = argparse.ArgumentParser(
        description="Analyse a towed-lure 6-DoF OpenFOAM run (roll rate, wobble "
        "frequency, sway, line angle, drag).",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    p.add_argument(
        "case",
        nargs="?",
        default=".",
        help="case directory generated by prepare_case.py (or its "
        "background/ sub-case)",
    )
    p.add_argument(
        "--source",
        choices=["auto", "log", "dat", "uniform"],
        default="auto",
        help="6-DoF state source",
    )
    p.add_argument("--log", default=None, help="explicit solver log file")
    p.add_argument(
        "--skip",
        type=float,
        default=None,
        help="initial transient to discard (s); default min(max(25%% of "
        "the run, 0.5 s), 50%% of the run)",
    )
    p.add_argument(
        "--fmin",
        type=float,
        default=0.5,
        help="lowest frequency considered for dominant peaks (Hz); the "
        "slow leader-pendulum mode lies below ~0.5 Hz",
    )
    p.add_argument("--fmax", type=float, default=None, help="highest frequency (Hz)")
    p.add_argument(
        "--out", default=None, help="output directory (default <case>/postprocess)"
    )
    p.add_argument("--no-plots", action="store_true", help="skip PNG output")
    return p


def main(argv=None):
    args = build_parser().parse_args(argv)
    root, bg = locate(Path(args.case))
    info_path = root / "case_info.json"
    info = json.loads(info_path.read_text()) if info_path.is_file() else None
    if info is None:
        print(
            "WARNING: case_info.json not found - attitude is relative to the first "
            "sample and line/drag coefficients are unavailable"
        )
    state = load_state(bg, args, info)
    if state is None:
        raise SystemExit(
            "No 6-DoF state found (looked for log.overPimpleDyMFoam with "
            "'report on', sixDoFRigidBodyState.dat, uniform/ states)"
        )
    forces = parse_forces(bg)
    S, sug, warnings, ser = analyse(state, forces, info, args)
    outdir = Path(args.out) if args.out else root / "postprocess"
    meta = dict(
        case=str(root),
        state_source=state["source"],
        n_samples=len(state["t"]),
        t_first=float(state["t"][0]),
        t_last=float(state["t"][-1]),
        force_source=None if forces is None else forces["source"],
    )
    pngs = write_outputs(outdir, S, sug, warnings, ser, meta, not args.no_plots)
    series = write_vtp_series(bg, outdir)

    print(
        f"State: {meta['state_source']} ({meta['n_samples']} samples, "
        f"t = {meta['t_first']:.4g} .. {meta['t_last']:.4g} s)"
    )
    print(f"Forces: {meta['force_source'] or 'none'}")
    print(f"\n{'metric':34s} {'value':>12s}  unit")
    for k, v in S.items():
        val = v["value"]
        sval = (
            "-"
            if val is None
            else (f"{val:.5g}" if isinstance(val, float) else str(val))
        )
        print(f"{k:34s} {sval:>12s}  {v['unit']}")
    if sug:
        print(
            "\nSuggested prepare_case.py options for a re-run: "
            + " ".join(f"--{k.replace('_', '-')} {v}" for k, v in sug.items())
        )
    for w in warnings:
        print(f"WARNING: {w}")
    print(
        f"\nWrote {outdir}/timeseries.csv, summary.csv, summary.json"
        + (f" and {len(pngs)} PNG(s)" if pngs else "")
    )
    for s in series:
        print(f"ParaView animation index: {s}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
