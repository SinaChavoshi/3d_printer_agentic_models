def locate(case: Path):
    case = case.resolve()
    if (case / "background").is_dir():
        return case, case / "background"
    if (case / "system").is_dir() and (case / "constant").is_dir():
        return case.parent if (case.parent / "case_info.json").is_file() else case, case
    raise SystemExit(
        f"{case}: neither a generated case (with background/) nor an "
        "OpenFOAM case directory"
    )


def load_state(bg, args, info):
    order = [args.source] if args.source != "auto" else ["log", "dat", "uniform"]
    for src in order:
        if src == "log":
            logs = (
                [Path(args.log)]
                if args.log
                else sorted(bg.glob("log.overPimpleDyMFoam*"))
            )
            for lg in logs:
                if lg.is_file():
                    st = parse_log(lg)
                    if st is not None and len(st["t"]) >= 2:
                        return st
        elif src == "dat":
            files = sorted(bg.glob("postProcessing/*/*/sixDoFRigidBodyState.dat"))
            if files:
                st = parse_state_dat(files)
                if st is not None and len(st["t"]) >= 2:
                    return st
        elif src == "uniform":
            Idiag = (
                info.get("mass", {}).get("principal_moments_kg_m2") if info else None
            )
            if Idiag is None:
                continue
            st = parse_uniform_states(bg, Idiag)
            if st is not None:
                return st
    return None


def analyse(state, forces, info, args):
    warnings = []
    t = state["t"]
    Q = state["Q"]
    mass = info.get("mass", {}) if info else {}
    leader = info.get("leader", {}) if info else {}
    flow = info.get("flow", {}) if info else {}
    geom = info.get("geometry", {}) if info else {}

    Q0 = np.array(mass["orientation_Q0"]) if "orientation_Q0" in mass else Q[0]
    cor0 = (
        np.array(mass["centre_of_mass_m"])
        if "centre_of_mass_m" in mass
        else state["cor"][0]
    )
    Rrel = np.einsum("nij,kj->nik", Q, Q0)  # Q(t) Q0^T
    eb = Rrel[:, :, 0]  # lure long axis (initially +x)
    p = np.einsum("ni,ni->n", state["omega"], eb)  # roll rate (rad/s)
    roll_cum = cumtrapz(p, t)
    yaw = np.degrees(np.arctan2(Rrel[:, 1, 0], Rrel[:, 0, 0]))
    pitch = np.degrees(-np.arcsin(np.clip(Rrel[:, 2, 0], -1, 1)))
    roll_w = np.degrees(np.arctan2(Rrel[:, 2, 1], Rrel[:, 2, 2]))
    com = state["com"]
    disp = com - com[0]

    def body_point(p0):
        return state["cor"] + np.einsum("nij,j->ni", Rrel, np.asarray(p0) - cor0)

    tail = body_point(geom["tail_point_m"]) if "tail_point_m" in geom else None

    line = None
    if "tow_point_m" in leader and "anchor_m" in leader:
        att = body_point(leader["tow_point_m"])
        line = np.asarray(leader["anchor_m"]) - att
    elif "leader" in state["restraints"]:
        line = -state["restraints"]["leader"]["vec"]  # attachment - anchor in log
    if line is not None:
        llen = np.linalg.norm(line, axis=1)
        elev = np.degrees(np.arctan2(line[:, 2], np.hypot(line[:, 0], line[:, 1])))
        azim = np.degrees(np.arctan2(line[:, 1], -line[:, 0]))
    else:
        llen = elev = azim = np.full(len(t), np.nan)
    if "leader" in state["restraints"]:
        rv = state["restraints"]["leader"]["vec"]  # attachment - anchor
        fv = state["restraints"]["leader"]["force"]
        tension = -np.einsum("ni,ni->n", fv, rv) / np.maximum(
            np.linalg.norm(rv, axis=1), 1e-300
        )
        tension_src = "log restraint report (signed: < 0 = spring in compression)"
    elif "stiffness_N_m" in leader:
        tension = leader["stiffness_N_m"] * (llen - leader["length_m"])
        tension_src = "spring law k*(length - restLength), damping omitted (signed)"
    else:
        tension = np.full(len(t), np.nan)
        tension_src = "unavailable"

    # Forces on the state time base
    F = None
    if forces is not None and len(forces["t"]) >= 2:
        F = np.column_stack(
            [
                np.interp(
                    t, forces["t"], forces["total"][:, j], left=np.nan, right=np.nan
                )
                for j in range(3)
            ]
        )

    # Analysis window
    t_end = t[-1]
    skip = (
        args.skip if args.skip is not None else min(max(0.25 * t_end, 0.5), 0.5 * t_end)
    )
    win = t >= t[0] + skip
    if win.sum() < 16:
        warnings.append("analysis window too short - using the whole record")
        win = np.ones_like(t, dtype=bool)
    tw = t[win]
    span = float(tw[-1] - tw[0]) if len(tw) > 1 else 0.0
    if span < 1.0:
        warnings.append(
            f"analysis window is only {span:.2f} s; frequencies below "
            f"~{2.0 / max(span, 1e-9):.1f} Hz are unreliable"
        )
    fmax = args.fmax if args.fmax else 0.5 / float(np.median(np.diff(tw)))

    S = {}

    def put(key, value, unit, desc):
        S[key] = dict(
            value=(
                None
                if value is None
                or (isinstance(value, float) and not math.isfinite(value))
                else value
            ),
            unit=unit,
            description=desc,
        )

    rate = p[win]
    put("analysis_start_s", float(tw[0]), "s", "start of the analysis window")
    put("analysis_span_s", span, "s", "length of the analysis window")
    put(
        "roll_rate_mean_rpm",
        float(rate.mean() * 60 / (2 * math.pi)),
        "rpm",
        "mean spin about the lure axis (+ = CCW seen from behind)",
    )
    put(
        "roll_rate_mean_rev_s",
        float(rate.mean() / (2 * math.pi)),
        "rev/s",
        "mean spin rate",
    )
    put(
        "roll_rate_std_rpm",
        float(rate.std() * 60 / (2 * math.pi)),
        "rpm",
        "spin-rate fluctuation (std)",
    )
    put(
        "rotations_in_window",
        float((roll_cum[win][-1] - roll_cum[win][0]) / (2 * math.pi)),
        "rev",
        "net rotations about the lure axis in the window",
    )
    put(
        "rotations_total",
        float(roll_cum[-1] / (2 * math.pi)),
        "rev",
        "net rotations over the whole run",
    )
    spinning = abs(rate.mean()) * span > 2 * math.pi  # > 1 rev in the window
    put("spinning", bool(spinning), "-", "true if > 1 net revolution in the window")
    rs = stats(roll_w[win])
    if not spinning:
        put("roll_angle_mean_deg", rs["mean"], "deg", "mean heel angle")
        put("roll_angle_p2p_deg", rs["p2p"], "deg", "roll rocking peak-to-peak")
        fr, ar, _ = dominant(tw, np.unwrap(np.radians(roll_w[win])), args.fmin, fmax)
        put("roll_rock_freq_hz", fr, "Hz", "dominant roll-rocking frequency")

    for key, sig, unit, desc in (
        ("yaw", yaw, "deg", "yaw (wobble) about +z"),
        ("pitch", pitch, "deg", "pitch (+ nose up)"),
        ("sway", disp[:, 1] * 1e3, "mm", "lateral CoM displacement (y)"),
        ("heave", disp[:, 2] * 1e3, "mm", "vertical CoM displacement (z)"),
        ("surge", disp[:, 0] * 1e3, "mm", "streamwise CoM displacement (x)"),
    ):
        st = stats(sig[win])
        put(f"{key}_mean_{unit}", st["mean"], unit, f"mean {desc}")
        put(f"{key}_std_{unit}", st["std"], unit, f"std of {desc}")
        put(f"{key}_p2p_{unit}", st["p2p"], unit, f"peak-to-peak {desc}")
        if key in ("yaw", "sway", "heave", "pitch"):
            fr, amp, _ = dominant(tw, sig[win], args.fmin, fmax)
            put(f"{key}_freq_hz", fr, "Hz", f"dominant frequency of {desc}")
            put(f"{key}_amp_{unit}", amp, unit, f"spectral peak amplitude of {desc}")
    if tail is not None:
        ty = (tail[:, 1] - tail[0, 1]) * 1e3
        st = stats(ty[win])
        put("tail_swing_p2p_mm", st["p2p"], "mm", "lateral tail-tip excursion p2p")
        fr, amp, _ = dominant(tw, ty[win], args.fmin, fmax)
        put("tail_swing_freq_hz", fr, "Hz", "dominant tail-swing frequency")

    put(
        "line_elevation_mean_deg",
        stats(elev[win])["mean"],
        "deg",
        "leader angle above horizontal towards the boat (+ = boat end higher)",
    )
    put(
        "line_azimuth_mean_deg",
        stats(azim[win])["mean"],
        "deg",
        "leader azimuth (+ = boat end towards +y)",
    )
    put(
        "line_tension_mean_N",
        stats(tension[win])["mean"],
        "N",
        f"leader tension ({tension_src})",
    )
    put("line_tension_std_N", stats(tension[win])["std"], "N", "leader tension std")
    tw_t = tension[win]
    tw_t = tw_t[np.isfinite(tw_t)]
    slack = float(np.mean(tw_t <= 0.0)) if len(tw_t) else None
    put(
        "line_slack_fraction",
        slack,
        "-",
        "fraction of samples with the leader spring in compression (a real, "
        "tension-only line would be slack)",
    )
    if slack is not None and slack > 0.01:
        warnings.append(
            f"leader spring in compression {100 * slack:.1f}% of the time: "
            "the linear-spring proxy pushes where a real line would go "
            "slack - interpret surge/line results with care"
        )
    lead_len = leader.get("length_m")
    if lead_len and "tow_point_m" in leader:
        height = -lead_len * math.sin(
            math.radians(S["line_elevation_mean_deg"]["value"] or 0.0)
        )
        put(
            "lure_height_above_leader_end_m",
            height,
            "m",
            "tow eye height relative to the boat-side leader end (+ = lure above, "
            "i.e. buoyant lure / line sloping down to the boat)",
        )

    U = flow.get("U_m_s")
    rho = flow.get("rho_kg_m3")
    A = geom.get("frontal_area_m2")
    if F is not None:
        Fw = F[win]
        ok = np.isfinite(Fw).all(axis=1)
        if ok.sum() > 8:
            Fw = Fw[ok]
            for j, (nm, desc) in enumerate(
                (
                    ("drag", "streamwise force Fx (drag)"),
                    ("side_force", "lateral force Fy"),
                    ("lift", "vertical force Fz"),
                )
            ):
                st = stats(Fw[:, j])
                put(f"{nm}_mean_N", st["mean"], "N", f"mean {desc}")
                put(f"{nm}_std_N", st["std"], "N", f"std of {desc}")
            fr, amp, _ = dominant(tw[ok], Fw[:, 1], args.fmin, fmax)
            put(
                "side_force_freq_hz",
                fr,
                "Hz",
                "dominant side-force frequency (vortex shedding / wobble)",
            )
            if U and rho and A:
                q = 0.5 * rho * U * U
                put(
                    "Cd_frontal",
                    float(np.mean(Fw[:, 0]) / (q * A)),
                    "-",
                    "drag coefficient on frontal area",
                )
                put(
                    "Cy_rms_frontal",
                    float(np.std(Fw[:, 1]) / (q * A)),
                    "-",
                    "rms side-force coefficient",
                )
    else:
        warnings.append("no force data (postProcessing/lureForces) found")

    # Re-run suggestions
    sug = {}
    if S.get("line_elevation_mean_deg", {}).get("value") is not None:
        sug["line_angle_deg"] = round(S["line_elevation_mean_deg"]["value"], 1)
    if S.get("Cd_frontal", {}).get("value") is not None:
        sug["cd_estimate"] = round(S["Cd_frontal"]["value"], 3)
    if info and "line_angle_deg" in sug:
        e0 = leader.get("elevation_deg")
        if e0 is not None and abs(sug["line_angle_deg"] - e0) > 5:
            warnings.append(
                f"mean leader elevation {sug['line_angle_deg']} deg differs "
                f"from the initial {e0:.1f} deg: re-generate with "
                f"--line-angle-deg {sug['line_angle_deg']} so the lure "
                "starts near equilibrium inside the refined region"
            )

    # Did the component mesh leave the refined motion box?
    if info and "mesh" in info:
        env = np.array(info["mesh"].get("motion_envelope_m", [np.inf] * 3))
        exceed = np.abs(disp).max(axis=0) > env
        if exceed.any():
            axes = "".join("xyz"[i] for i in range(3) if exceed[i])
            warnings.append(
                f"lure moved beyond the refined motion envelope along "
                f"{axes}: overset donors there are coarser - enlarge "
                "--envelope/--vertical-envelope or fix the line angle"
            )

    series = dict(
        t=t,
        disp=disp,
        com=com,
        roll_cum=roll_cum,
        rate=p,
        yaw=yaw,
        pitch=pitch,
        roll_w=roll_w,
        tail=tail,
        elev=elev,
        azim=azim,
        llen=llen,
        tension=tension,
        F=F,
        win=win,
        fmin=args.fmin,
        fmax=fmax,
    )
    return S, sug, warnings, series


